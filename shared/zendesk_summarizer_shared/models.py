class SummaryStructured(BaseModel):
    """Structured breakdown of a ticket conversation generated by AI."""
    executive_summary: str = Field(
        default="",
        description="Brief 1-2 sentence high-level overview of the ticket situation"
    )
    customer_issue: str = Field(
        ...,
        description="The primary root problem or query reported by the customer"
    )
    customer_expectations: Optional[str] = Field(
        default=None,
        description="What the customer explicitly expects or desires as an outcome"
    )
    business_impact: Optional[str] = Field(
        default=None,
        description="Severity and impact on customer business or operations"
    )
    technical_symptoms: List[str] = Field(
        default_factory=list,
        description="Observed technical symptoms, error codes, or failure modes"
    )
    attempted_troubleshooting: List[str] = Field(
        default_factory=list,
        description="Troubleshooting steps or diagnostic actions already tried"
    )
    root_cause: Optional[str] = Field(
        default=None,
        description="Root cause only when supported by evidence; explicitly 'Undetermined' if unknown"
    )
    actions_taken: List[str] = Field(
        default_factory=list,
        description="Chronological key actions, troubleshooting steps, or answers provided so far"
    )
    current_status: str = Field(
        ...,
        description="Current state of the ticket (e.g. 'Awaiting customer reply', 'Investigating bug', 'Resolved')"
    )
    commitments: List[str] = Field(
        default_factory=list,
        description="Any commitments, promises, or ETAs made to the customer"
    )
    deadlines: List[str] = Field(
        default_factory=list,
        description="Specific deadlines, SLA thresholds, or promised target times"
    )
    responsible_party: Optional[str] = Field(
        default=None,
        description="Individual, team, or party owning the current next step"
    )
    action_items: List[str] = Field(
        default_factory=list,
        description="Recommended next steps or pending action items for the support agent"
    )
    sentiment: str = Field(
        default="neutral",
        description="Detected customer sentiment (e.g. 'positive', 'neutral', 'frustrated', 'urgent')"
    )
    urgency_level: str = Field(
        default="normal",
        description="Urgency estimate: 'low', 'normal', 'high', 'critical'"
    )
    notes: List[str] = Field(
        default_factory=list,
        description="Notable observations or internal triage notes"
    )
    summary_profile: str = Field(
        default="standard",
        description="The profile used to generate this summary"
    )

    def to_markdown(self) -> str:
        """Convert the structured summary into clean, formatted markdown for Zendesk internal notes."""
        sentiment_emoji = {
            "positive": "🟢 Positive",
            "neutral": "⚪ Neutral",
            "frustrated": "🟠 Frustrated",
            "urgent": "🔴 Urgent",
            "negative": "🔴 Negative",
        }.get(self.sentiment.lower(), f"⚪ {self.sentiment.title()}")

        urgency_badge = {
            "low": "🔵 Low",
            "normal": "⚪ Normal",
            "high": "🟠 High",
            "critical": "🚨 Critical",
        }.get(self.urgency_level.lower(), f"⚪ {self.urgency_level.title()}")

        profile_label = f" — {self.summary_profile.title()}" if self.summary_profile and self.summary_profile != "standard" else ""
        lines = [
            f"### 🤖 AI Ticket Summary{profile_label}",
        ]

        if self.executive_summary:
            lines.extend([
                f"**Executive Summary:** {self.executive_summary}",
                "",
            ])

        lines.extend([
            f"**Customer Issue:** {self.customer_issue}",
            "",
            f"**Current Status:** {self.current_status} | **Sentiment:** {sentiment_emoji} | **Urgency:** {urgency_badge}",
            "",
        ])

        if self.customer_expectations:
            lines.extend([f"**Customer Expectations:** {self.customer_expectations}", ""])

        if self.business_impact:
            lines.extend([f"**Business Impact:** {self.business_impact}", ""])

        if self.technical_symptoms:
            lines.append("**Technical Symptoms / Errors:**")
            for symptom in self.technical_symptoms:
                lines.append(f"- ⚠️ {symptom}")
            lines.append("")

        if self.attempted_troubleshooting or self.actions_taken:
            lines.append("**Actions Taken / Troubleshooting:**")
            actions = self.attempted_troubleshooting or self.actions_taken
            for action in actions:
                lines.append(f"- {action}")
            lines.append("")

        if self.root_cause:
            lines.extend([f"**Root Cause:** {self.root_cause}", ""])

        if self.commitments:
            lines.append("**Commitments / Promised Follow-ups:**")
            for comm in self.commitments:
                lines.append(f"- ⏳ {comm}")
            lines.append("")

        if self.deadlines:
            lines.append("**Deadlines & Targets:**")
            for dl in self.deadlines:
                lines.append(f"- 📅 {dl}")
            lines.append("")

        if self.responsible_party:
            lines.extend([f"**Owner:** {self.responsible_party}", ""])

        if self.action_items:
            lines.append("**Next Steps / Action Items:**")
            for item in self.action_items:
                lines.append(f"- [ ] {item}")
            lines.append("")

        if self.notes:
            lines.append("**Triage Notes:**")
            for note in self.notes:
                lines.append(f"- {note}")
            lines.append("")

        lines.append("*Generated by Zendesk Support Intelligence Platform (Verified Facts vs Hypotheses distinguished)*")
        return "\n".join(lines)


