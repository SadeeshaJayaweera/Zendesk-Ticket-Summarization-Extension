"""Domain and API data models for Zendesk Ticket Summarizer."""

from datetime import datetime
from typing import Any, Dict, List, Optional, Union
from pydantic import BaseModel, Field



# --- Zendesk API Data Models ---

class ZendeskAttachment(BaseModel):
    """Zendesk file attachment metadata."""
    id: Optional[int] = None
    file_name: Optional[str] = None
    content_url: Optional[str] = None
    content_type: Optional[str] = None
    size: Optional[int] = None


class ZendeskUser(BaseModel):
    """Represents a Zendesk user (requester, assignee, or collaborator)."""
    id: int
    name: str
    email: Optional[str] = None
    role: Optional[str] = "end-user"
    active: Optional[bool] = True
    organization_id: Optional[int] = None
    created_at: Optional[datetime] = None
    updated_at: Optional[datetime] = None
    time_zone: Optional[str] = None
    phone: Optional[str] = None


class ZendeskComment(BaseModel):
    """Represents a single comment in a Zendesk ticket conversation thread."""
    id: int
    type: str = "Comment"
    author_id: int
    body: str
    html_body: Optional[str] = None
    plain_body: Optional[str] = None
    public: bool = True
    attachments: List[ZendeskAttachment] = Field(default_factory=list)
    created_at: Optional[datetime] = None
    audit_id: Optional[int] = None


class ZendeskTicket(BaseModel):
    """Represents a Zendesk ticket with core metadata."""
    id: int
    url: Optional[str] = None
    subject: str = ""
    description: Optional[str] = None
    status: str = "open"
    priority: Optional[str] = "normal"
    requester_id: Optional[int] = None
    submitter_id: Optional[int] = None
    assignee_id: Optional[int] = None
    organization_id: Optional[int] = None
    tags: List[str] = Field(default_factory=list)
    created_at: Optional[datetime] = None
    updated_at: Optional[datetime] = None


# Canonical model aliases matching Zendesk entity names
User = ZendeskUser
Ticket = ZendeskTicket
Comment = ZendeskComment
Attachment = ZendeskAttachment


class UserResponse(BaseModel):
    """Zendesk API response for single user retrieval."""
    user: ZendeskUser


class TicketResponse(BaseModel):
    """Zendesk API response for single ticket retrieval."""
    ticket: ZendeskTicket
    users: Optional[List[ZendeskUser]] = None
    audit: Optional[Any] = None


class TicketCommentsResponse(BaseModel):
    """Zendesk API response for ticket comments retrieval."""
    comments: List[ZendeskComment] = Field(default_factory=list)
    count: int = 0
    next_page: Optional[str] = None
    previous_page: Optional[str] = None



# --- AI Summarization Structured Models ---

class SummaryStructured(BaseModel):
    """Structured breakdown of a ticket conversation generated by AI."""
    executive_summary: str = Field(
        default="",
        description="Brief 1-2 sentence high-level overview of the ticket situation"
    )
    customer_issue: str = Field(
        ...,
        description="The primary root problem or query reported by the customer"
    )
    actions_taken: List[str] = Field(
        default_factory=list,
        description="Chronological key actions, troubleshooting steps, or answers provided so far"
    )
    current_status: str = Field(
        ...,
        description="Current state of the ticket (e.g. 'Awaiting customer reply', 'Investigating bug', 'Resolved')"
    )
    commitments: List[str] = Field(
        default_factory=list,
        description="Any commitments, promises, or ETAs made to the customer"
    )
    action_items: List[str] = Field(
        default_factory=list,
        description="Recommended next steps or pending action items for the support agent"
    )
    sentiment: str = Field(
        default="neutral",
        description="Detected customer sentiment (e.g. 'positive', 'neutral', 'frustrated', 'urgent')"
    )
    notes: List[str] = Field(
        default_factory=list,
        description="Notable observations or internal triage notes"
    )

    def to_markdown(self) -> str:
        """Convert the structured summary into clean, formatted markdown for Zendesk internal notes."""
        sentiment_emoji = {
            "positive": "🟢 Positive",
            "neutral": "⚪ Neutral",
            "frustrated": "🟠 Frustrated",
            "urgent": "🔴 Urgent",
        }.get(self.sentiment.lower(), f"⚪ {self.sentiment.title()}")

        lines = [
            "### 🤖 AI Ticket Summary",
        ]

        if self.executive_summary:
            lines.extend([
                f"**Executive Summary:** {self.executive_summary}",
                "",
            ])

        lines.extend([
            f"**Customer Issue:** {self.customer_issue}",
            "",
            f"**Current Status:** {self.current_status} | **Sentiment:** {sentiment_emoji}",
            "",
        ])

        if self.actions_taken:
            lines.append("**Actions Taken / Troubleshooting:**")
            for action in self.actions_taken:
                lines.append(f"- {action}")
            lines.append("")

        if self.commitments:
            lines.append("**Commitments / Promised Follow-ups:**")
            for comm in self.commitments:
                lines.append(f"- ⏳ {comm}")
            lines.append("")

        if self.action_items:
            lines.append("**Next Steps / Action Items:**")
            for item in self.action_items:
                lines.append(f"- [ ] {item}")
            lines.append("")

        if self.notes:
            lines.append("**Triage Notes:**")
            for note in self.notes:
                lines.append(f"- {note}")
            lines.append("")

        lines.append("*Generated automatically by Support AI Assistant*")
        return "\n".join(lines)


# Canonical alias
TicketSummary = SummaryStructured



# --- DTO / API Request & Response Models ---

class SummarizeRequest(BaseModel):
    """Request parameters for generating an AI summary."""
    ticket_id: Optional[int] = None
    summary_style: str = Field(
        default="standard",
        description="Style of summary: 'standard', 'brief', 'action_only', or 'detailed'"
    )


class DirectSummarizeRequest(BaseModel):
    """Request for summarizing custom text or conversation transcript without fetching Zendesk ticket."""
    text: str = Field(..., description="Raw text or conversation transcript to summarize")
    subject: Optional[str] = Field(default=None, description="Optional ticket subject or title")
    summary_style: str = Field(default="standard", description="Summary style")


class SummarizeResponse(BaseModel):
    """Response containing structured AI summary and ready-to-use markdown note."""
    ticket_id: Optional[int] = None
    subject: Optional[str] = None
    summary: SummaryStructured
    markdown_note: str
    model_used: str


class PostNoteRequest(BaseModel):
    """Request payload to post a note to a Zendesk ticket."""
    body: str = Field(..., description="Content of the note to post")
    public: bool = Field(
        default=False,
        description="Whether the note is public (true) or private internal note (false). Default is False (Private Note)."
    )


class PostNoteResponse(BaseModel):
    """Response confirming note creation on Zendesk."""
    ticket_id: int
    comment_id: Optional[int] = None
    is_public: bool
    status: str = "success"
    message: str = "Internal note posted successfully"
    created_at: Optional[datetime] = None


class TicketDetailResponse(BaseModel):
    """Aggregated ticket details and conversation comments."""
    ticket: ZendeskTicket
    comments: List[ZendeskComment]
    total_comments: int


class TicketHistorySummaryItem(BaseModel):
    """Represents a historical AI summary note retrieved from ticket comments."""
    id: int
    author_id: int
    created_at: Optional[datetime] = None
    body: str
    is_internal: bool = True
    preview: str = ""


class PendingDraft(BaseModel):
    """Represents an automated AI pre-draft awaiting agent review."""
    ticket_id: int
    status: str = "pending_review"  # pending_review, posted, dismissed
    summary: SummaryStructured
    markdown_note: str
    source_trigger: str = "zendesk_webhook_solved"
    created_at: datetime = Field(default_factory=datetime.utcnow)
    updated_at: datetime = Field(default_factory=datetime.utcnow)


class PendingDraftResponse(BaseModel):
    """Response containing pending review draft if available."""
    ticket_id: int
    has_pending_draft: bool
    draft: Optional[PendingDraft] = None


class TicketHistoryResponse(BaseModel):
    """Response containing past AI summaries for a ticket."""
    ticket_id: int
    summaries: List[TicketHistorySummaryItem]
    total: int
    pending_draft: Optional[PendingDraft] = None


class WebhookTicketPayload(BaseModel):
    """Zendesk webhook event payload structure."""
    id: Optional[Union[int, str]] = None
    ticket_id: Optional[Union[int, str]] = None
    status: Optional[str] = None
    subject: Optional[str] = None
    event_type: Optional[str] = None
    ticket: Optional[Dict[str, Any]] = None



